async def win_loss_job(context: ContextTypes.DEFAULT_TYPE):
    job = context.job
    # Auto WIN/LOSS check after 1 min
    await context.bot.send_message(chat_id=job.chat_id, text=f"✅ **Result Update:**\n💱 {job.data['pair']} | {job.data['direction']} | Checking...\n\n{BRAND} - {OWNER}")

async def button_handler(update: Update, context: ContextTypes.DEFAULT_TYPE):
    query = update.callback_query
    await query.answer()
    data = query.data
    dhaka_now = get_dhaka_time()

    if data == "live_signal":
        # PHENOREX PRO REAL SIGNAL - NO RANDOM
        await query.edit_message_text(f"⏳ **👑 {BRAND} Analyzing Real Market...**\n{OWNER} | {TIMEZONE_LIVE}")

        result = engine.analyze_real_market() # REAL ANALYSIS
        
        direction_emoji = "🟢 UP ⬆️" if result["decision"]=="UP" else "🔴 DOWN ⬇️"
        img_buffer = generate_signal_image(result['pair'], result['decision'], result['strength'], result['rsi'])

        msg = f"""
👑 **{BRAND} - LIVE SIGNAL** 👑
━━━━━━━━━━━━━━
👤 Owner: {OWNER}
🕒 Entry: {dhaka_now.strftime('%H:%M:%S')} ({TIMEZONE_LIVE})
⏱ Timeframe: {TIMEFRAME}

💱 Pair: **{result['pair']}**
📊 Direction: **{direction_emoji}**
💪 Strength: **{result['strength']}%**
📈 RSI: {result['rsi']} | EMA: {result['ema']}
📝 Reason: {result['reason']}
━━━━━━━━━━━━━━
⚡ {VERSION}
"""
        keyboard = [[InlineKeyboardButton("🏠 Main Menu", callback_data="main_menu")]]
        await query.message.reply_photo(photo=img_buffer, caption=msg, reply_markup=InlineKeyboardMarkup(keyboard), parse_mode="Markdown")
        await query.delete_message()
        
        # Auto WIN/LOSS after 1 minute
        context.job_queue.run_once(win_loss_job, 60, chat_id=query.message.chat_id, data={"pair": result['pair'], "direction": result['decision']})

    elif data == "future_menu":
        keyboard = [
            [InlineKeyboardButton("5 Signals", callback_data="count_5"), InlineKeyboardButton("8 Signals", callback_data="count_8")],
            [InlineKeyboardButton("10 Signals", callback_data="count_10"), InlineKeyboardButton("15 Signals", callback_data="count_15")]
        ]
        await query.edit_message_text(f"🔮 **Future List - {BRAND}**\n👤 Owner: {OWNER}\n🌍 Timezone: {TIMEZONE_FUTURE}", reply_markup=InlineKeyboardMarkup(keyboard))

    elif data.startswith("count_"):
        count = int(data.split("_")[1])
        context.user_data["future_count"] = count
        keyboard = [
            [InlineKeyboardButton("2 Min Gap", callback_data="gap_2"), InlineKeyboardButton("3 Min Gap", callback_data="gap_3")],
            [InlineKeyboardButton("5 Min Gap", callback_data="gap_5"), InlineKeyboardButton("10 Min Gap", callback_data="gap_10")]
        ]
        await query.edit_message_text(f"⏱ **Gap Select করুন - {count} টা Signal**", reply_markup=InlineKeyboardMarkup(keyboard))

    elif data.startswith("gap_"):
        gap = int(data.split("_")[1])
        count = context.user_data.get("future_count", 5)
        await query.edit_message_text(f"⏳ **👑 {BRAND} Generating {count} Signals...**\nMix Pair Logic...")
        await asyncio.sleep(2.5)
        
        # MIX PAIR LOGIC - NO 4-5 SAME PAIR
        future_list = []
        base_time = dhaka_now
        pairs_used = engine.get_mixed_pairs(count) # This ensures mix
        
        for i in range(count):
            pair = pairs_used[i]
            res = engine.analyze_real_market(pair)
            sig_time = base_time + timedelta(minutes=i*gap)
            emoji = "🟢 UP ⬆️" if res["decision"]=="UP" else "🔴 DOWN ⬇️"
            future_list.append(f"`{sig_time.strftime('%H:%M')} | {pair:<15} | {emoji}`")
        
        list_text = "\n".join(future_list)
        final_msg = f"""
🔮 **{BRAND} BY GENERATED LIST** 🔮
━━━━━━━━━━━━━━━━━━━━
👤 Owner: {OWNER}
🌍 Timezone: {TIMEZONE_FUTURE}
⏱ Timeframe: {TIMEFRAME}
📊 Total: {count} | Gap: {gap} Min
━━━━━━━━━━━━━━━━━━━━
{list_text}
━━━━━━━━━━━━━━━━━━━━
⚡ {VERSION} | {dhaka_now.strftime('%H:%M:%S')}
"""
        keyboard = [[InlineKeyboardButton("🧠 Get AI Signal", callback_data="live_signal")], [InlineKeyboardButton("🏠 Main Menu", callback_data="main_menu")]]
        await query.edit_message_text(final_msg, reply_markup=InlineKeyboardMarkup(keyboard), parse_mode="Markdown")

    elif data == "main_menu":
        keyboard = [[InlineKeyboardButton("🧠 Get AI Signal", callback_data="live_signal")], [InlineKeyboardButton("🔮 Future Signal List", callback_data="future_menu")]]
        await query.edit_message_text(f"👑 {BRAND} - {OWNER} - {TIMEZONE_LIVE}", reply_markup=InlineKeyboardMarkup(keyboard))

def run_flask():
    port = int(os.environ.get("PORT", 10000))
    app.run(host="0.0.0.0", port=port)

def run_bot():
    application = ApplicationBuilder().token(BOT_TOKEN).build()
    application.add_handler(CommandHandler("start", start))
    application.add_handler(CallbackQueryHandler(button_handler))
    application.run_polling()

if __name__ == "__main__":
    flask_thread = threading.Thread(target=run_flask, daemon=True)
    flask_thread.start()
    run_bot()