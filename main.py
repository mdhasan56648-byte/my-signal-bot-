import os
import asyncio
from datetime import datetime, timedelta
from flask import Flask
import threading

from telegram import Update, InlineKeyboardButton, InlineKeyboardMarkup
from telegram.ext import ApplicationBuilder, CommandHandler, CallbackQueryHandler, ContextTypes
import trading_engine as engine

# --- CONFIG ---
BOT_TOKEN = os.getenv("BOT_TOKEN", "YOUR_BOT_TOKEN_HERE")
OWNER = "MD HASAN"
TIMEZONE = "UTC+6 Dhaka (Bangladesh)"
TIMEFRAME = "1 Minute"

app = Flask(__name__)

@app.route("/")
def home():
    return f"FINOREX PREMIUM BOT - Owner {OWNER} - {TIMEZONE} - LIVE"

# --- TELEGRAM BOT ---
def get_dhaka_time():
    # UTC+6
    return datetime.utcnow() + timedelta(hours=6)

async def start(update: Update, context: ContextTypes.DEFAULT_TYPE):
    keyboard = [
        [InlineKeyboardButton("📈 GET AI SIGNAL (LIVE)", callback_data="live_signal")],
        [InlineKeyboardButton("🔮 FUTURE SIGNAL LIST", callback_data="future_menu")],
        [InlineKeyboardButton("⏰ Timeframe: 1 Minute", callback_data="tf_info"),
         InlineKeyboardButton("🌍 Market: OTC", callback_data="market_info")]
    ]
    text = f"""
🔥 **FINOREX PREMIUM BOT** 🔥
👤 Owner: {OWNER}
🌍 Timezone: {TIMEZONE}
⏱ Timeframe: {TIMEFRAME}
📊 Pairs: Quotex OTC (20 Pairs)

নিচে থেকে সিলেক্ট করুন 👇
"""
    await update.message.reply_text(text, reply_markup=InlineKeyboardMarkup(keyboard), parse_mode="Markdown")

async def button_handler(update: Update, context: ContextTypes.DEFAULT_TYPE):
    query = update.callback_query
    await query.answer()
    data = query.data
    dhaka_now = get_dhaka_time()

    if data == "live_signal":
        # INSTANT SIGNAL - NO DELAY
        import random
        pair = random.choice(engine.QUOTEX_OTC_PAIRS)
        result = engine.analyze_fast(pair)
        
        direction_emoji = "🟢 UP" if result["decision"]=="UP" else "🔴 DOWN"
        
        msg = f"""
📈 **LIVE SIGNAL - FINOREX**
━━━━━━━━━━━━━━
👤 Owner: {OWNER}
🕒 Time: {dhaka_now.strftime('%H:%M:%S')} ({TIMEZONE})
⏱ Timeframe: {TIMEFRAME}

💱 Pair: **{result['pair']}**
📊 Direction: **{direction_emoji}**
💪 Strength: **{result['strength']}**
📈 RSI: {result['rsi']}
📝 Reason: {result['reason']}
━━━━━━━━━━━━━━
⚡ Generated by FINOREX ULTRA FAST
"""
        keyboard = [[InlineKeyboardButton("🔄 Next Signal", callback_data="live_signal")],
                    [InlineKeyboardButton("🏠 Main Menu", callback_data="main_menu")]]
        await query.edit_message_text(msg, reply_markup=InlineKeyboardMarkup(keyboard), parse_mode="Markdown")

    elif data == "future_menu":
        keyboard = [
            [InlineKeyboardButton("5 Signals", callback_data="count_5"),
             InlineKeyboardButton("8 Signals", callback_data="count_8")],
            [InlineKeyboardButton("10 Signals", callback_data="count_10"),
             InlineKeyboardButton("15 Signals", callback_data="count_15")]
        ]
        await query.edit_message_text(f"🔮 **Future Signal Count Select করুন**\n👤 Owner: {OWNER}\n🕒 {TIMEZONE}", reply_markup=InlineKeyboardMarkup(keyboard))

    elif data.startswith("count_"):
        count = int(data.split("_")[1])
        context.user_data["future_count"] = count
        keyboard = [
            [InlineKeyboardButton("2 Min Gap", callback_data="gap_2"),
             InlineKeyboardButton("3 Min Gap", callback_data="gap_3")],
            [InlineKeyboardButton("5 Min Gap", callback_data="gap_5"),
             InlineKeyboardButton("10 Min Gap", callback_data="gap_10")]
        ]
        await query.edit_message_text(f"⏱ **Gap Select করুন - {count} টা Signal এর জন্য**", reply_markup=InlineKeyboardMarkup(keyboard))

    elif data.startswith("gap_"):
        gap = int(data.split("_")[1])
        count = context.user_data.get("future_count", 5)
        
        # 2.5 Sec Buffer - FINOREX Style
        await query.edit_message_text(f"⏳ **FINOREX Generating {count} Signals...**\n2.5 Sec Buffering... {OWNER}")
        await asyncio.sleep(2.5)
        
        # GENERATE LIST - FINOREX BY GENERATED LIST (NOT RED DRAGON)
        future_list = []
        base_time = dhaka_now
        import random
        for i in range(count):
            pair = random.choice(engine.QUOTEX_OTC_PAIRS)
            res = engine.analyze_fast(pair)
            sig_time = base_time + timedelta(minutes=i*gap)
            emoji = "🟢" if res["decision"]=="UP" else "🔴"
            future_list.append(f"`{sig_time.strftime('%H:%M')} | {pair:<15} | {emoji} {res['decision']}`")
        
        list_text = "\n".join(future_list)
        
        final_msg = f"""
🔮 **FINOREX BY GENERATED LIST**
━━━━━━━━━━━━━━━━━━━━
👤 Owner: {OWNER}
🌍 Timezone: {TIMEZONE}
⏱ Timeframe: {TIMEFRAME}
📊 Total: {count} Signals | Gap: {gap} Min
━━━━━━━━━━━━━━━━━━━━
{list_text}
━━━━━━━━━━━━━━━━━━━━
⚡ Generated: {dhaka_now.strftime('%H:%M:%S')} Dhaka
"""
        keyboard = [[InlineKeyboardButton("🔄 New Future List", callback_data="future_menu")],
                    [InlineKeyboardButton("🏠 Main Menu", callback_data="main_menu")]]
        await query.edit_message_text(final_msg, reply_markup=InlineKeyboardMarkup(keyboard), parse_mode="Markdown")

    elif data == "main_menu":
        keyboard = [
            [InlineKeyboardButton("📈 GET AI SIGNAL (LIVE)", callback_data="live_signal")],
            [InlineKeyboardButton("🔮 FUTURE SIGNAL LIST", callback_data="future_menu")]
        ]
        await query.edit_message_text(f"🔥 FINOREX PREMIUM - {OWNER} - {TIMEZONE}", reply_markup=InlineKeyboardMarkup(keyboard))

def run_flask():
    port = int(os.environ.get("PORT", 10000))
    app.run(host="0.0.0.0", port=port)

def run_bot():
    application = ApplicationBuilder().token(BOT_TOKEN).build()
    application.add_handler(CommandHandler("start", start))
    application.add_handler(CallbackQueryHandler(button_handler))
    application.run_polling()

if __name__ == "__main__":
    # Flask + Telegram Threading - 100% Deploy Success Formula
    flask_thread = threading.Thread(target=run_flask, daemon=True)
    flask_thread.start()
    run_bot()