def get_dhaka_time():
    return datetime.utcnow() + timedelta(hours=6)

# --- IMAGE SIGNAL CARD GENERATOR - PHENOREX PRO STYLE ---
def generate_signal_image(pair, direction, strength, rsi):
    # Create Chart Image 800x500
    W, H = 800, 500
    img = Image.new('RGB', (W, H), color='#0d1117')
    draw = ImageDraw.Draw(img)
    
    # Try to load font, fallback to default
    try:
        font_big = ImageFont.truetype("arial.ttf", 32)
        font_mid = ImageFont.truetype("arial.ttf", 22)
        font_small = ImageFont.truetype("arial.ttf", 18)
    except:
        font_big = ImageFont.load_default()
        font_mid = ImageFont.load_default()
        font_small = ImageFont.load_default()

    # Header - PHENOREX PRO with Crown
    draw.rectangle([0, 0, W, 70], fill='#161b22')
    draw.text((20, 15), f"👑 {BRAND}", font=font_big, fill='#f1c40f')
    draw.text((W-200, 20), f"{TIMEZONE_LIVE}", font=font_mid, fill='white')

    # Fake Candles for visual
    import random
    x = 50
    for _ in range(25):
        open_p = random.randint(100, 300)
        close_p = open_p + random.randint(-40, 40)
        color = '#00ff88' if close_p > open_p else '#ff4444'
        draw.line([x, 120+open_p, x, 120+close_p], fill=color, width=6)
        x += 28

    # Signal Box
    arrow = "⬆️" if direction == "UP" else "⬇️"
    dir_color = '#00ff88' if direction == "UP" else '#ff4444'
    dir_text = f"{direction} {arrow}"
    
    draw.rectangle([50, 380, W-50, 470], fill='#161b22', outline=dir_color, width=3)
    draw.text((70, 390), f"{pair} | {dir_text}", font=font_big, fill=dir_color)
    draw.text((70, 430), f"RSI: {rsi} | Strength: {strength} | Owner: {OWNER}", font=font_small, fill='white')
    draw.text((W-250, 475), VERSION, font=font_small, fill='#8b949e')

    bio = io.BytesIO()
    img.save(bio, 'PNG')
    bio.seek(0)
    return bio

